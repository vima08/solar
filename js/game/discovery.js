export function discoveryLog(story) {
  const entries = [];
  if (story.stage !== "unheard") entries.push("Принят позывной зонда «Ласточка». Координаты: Европа.");
  if (["choice", "return", "completed"].includes(story.stage)) entries.push("Открыт архив наблюдений тепловой трещины во льду Европы.");
  if (["return", "completed"].includes(story.stage)) entries.push(story.choice === "open" ? "Выбор: открытая публикация. Получено40 кр.; приглашение на Землю." : "Выбор: сохранить регистратор. Заказ «Ареса» на Марсе:110 кр.");
  if (story.stage === "completed") entries.push(story.choice === "open" ? "Наблюдения переданы на Земле. Получено ещё30 кр.; итого70." : "Регистратор сдан на Марсе. Получено110 кр.; грузовое место освобождено.");
  return entries;
}
