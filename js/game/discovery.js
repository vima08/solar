import { CAREER_VERSION, normalizeCareer } from "./contracts.js";
import { usedSpace, CAPACITY } from "./cargo.js";
import { EUROPA } from "./discovery-state.js";

export function discoveryDestination(story) {
  return story.stage === "return" ? story.choice === "open" ? "earth" : "mars" : EUROPA;
}

export function discoveryTransition(career, action, landedOn, expectedStage) {
  if (career?.version !== CAREER_VERSION || normalizeCareer(career).issue) return { error: "Данные карьеры требуют восстановления." };
  const story = career.discovery;
  if (story.stage !== expectedStage) return { error: "Этап истории изменился. Перечитайте журнал." };
  if (career.contractStatus !== "completed") return { error: "Сначала завершите доставку аппаратуры на Марс." };
  let next;
  let reward = 0;
  if (action === "listen" && story.stage === "unheard") next = { stage: "signal", choice: null };
  else if (action === "survey" && story.stage === "signal") {
    if (landedOn !== EUROPA) return { error: "Для исследования маяка выполните посадку на Европу." };
    next = { stage: "choice", choice: null };
  } else if (["open", "salvage"].includes(action) && story.stage === "choice") {
    if (landedOn !== EUROPA) return { error: "Выберите судьбу архива после посадки на Европу." };
    if (action === "salvage" && usedSpace(career) >= CAPACITY) return { error: "Регистратору нужно 1 свободное место. Продайте товар в порту или опубликуйте данные без груза." };
    next = { stage: "return", choice: action };
    reward = action === "open" ? 40 : 0;
  } else if (action === "finish" && story.stage === "return") {
    if (landedOn !== discoveryDestination(story)) return { error: `Для сдачи выполните посадку: ${story.choice === "open" ? "Земля" : "Марс"}.` };
    next = { ...story, stage: "completed" };
    reward = story.choice === "open" ? 30 : 110;
  } else return { error: "Действие уже выполнено или недоступно на этом этапе." };
  if (!Number.isSafeInteger(career.credits + reward)) return { error: "Баланс достиг допустимого предела. Награда и этап не изменены." };
  return { career: { ...career, credits: career.credits + reward, discovery: next } };
}

